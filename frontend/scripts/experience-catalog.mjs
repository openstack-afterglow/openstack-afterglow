// @ts-check
/** Static, parameter-free message templates for diagnostic restoration, never rendered event text. */
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCatalogs, LOCALES } from './i18n-core.mjs';
import { parseMessage } from '../src/lib/i18n/messageFormat.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

/** @param {Awaited<ReturnType<typeof loadCatalogs>>} catalogs */
export function buildExperienceCatalog(catalogs) {
	if (catalogs.loadErrors.length) throw new Error('Cannot generate experience catalog from invalid source catalogs');
	/** @type {Record<string, Record<string, string>>} */
	const messages = {};
	for (const namespace of [...catalogs.namespaces].sort()) {
		if (!/^[a-z][a-z0-9-]*$/.test(namespace)) throw new Error('Invalid source namespace');
		// Korean source defines the registry; translation-only/dynamic keys are never registered.
		for (const key of Object.keys(catalogs.messages.ko?.[namespace] ?? {}).sort()) {
			if (!/^[a-z][A-Za-z0-9]*(?:\.[A-Za-z0-9_]+)*$/.test(key)) throw new Error('Invalid source message key');
			/** @type {Record<string, string>} */
			const templates = {};
			for (const locale of LOCALES) {
				const template = catalogs.messages[locale]?.[namespace]?.[key];
				if (typeof template !== 'string') continue;
				try { parseMessage(template); } catch { continue; }
				templates[locale] = template;
			}
			if (Object.keys(templates).length) messages[`${namespace}:${key}`] = templates;
		}
	}
	const revision = createHash('sha256').update(JSON.stringify(messages)).digest('hex');
	return { schema_version: 1, revision, messages };
}

/** @param {string[]} [args] */
export async function generateExperienceCatalog(args = process.argv.slice(2)) {
	if (args.some((arg) => arg !== '--check')) throw new Error('Usage: experience-catalog.mjs [--check]');
	const catalog = buildExperienceCatalog(await loadCatalogs());
	const namespaces = [...new Set(Object.keys(catalog.messages).map((key) => key.split(':')[0]))].sort();
	const outputs = [
		['backend/app/data/experience_catalog.json', `${JSON.stringify(catalog)}\n`],
		['frontend/src/lib/i18n/experienceCatalogRevision.ts', `// Generated by frontend/scripts/experience-catalog.mjs. Do not edit.\nexport const EXPERIENCE_CATALOG_REVISION = '${catalog.revision}';\nexport const EXPERIENCE_CATALOG_NAMESPACES: ReadonlySet<string> = new Set(${JSON.stringify(namespaces)});\n`],
	];
	for (const [relative, content] of outputs) {
		const target = path.join(root, relative);
		if (args.includes('--check')) {
			let actual;
			try { actual = await readFile(target, 'utf8'); } catch { actual = undefined; }
			if (actual !== content) throw new Error(`Stale experience catalog artifact: ${relative}`);
		} else {
			await mkdir(path.dirname(target), { recursive: true });
			await writeFile(target, content, 'utf8');
		}
	}
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	generateExperienceCatalog().catch((error) => {
		console.error(error.message);
		process.exitCode = 1;
	});
}
